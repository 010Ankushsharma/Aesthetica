  static List<Exercise> _buildExercises() {
    final exercises = <Exercise>[];
    final seeds = _baseSeeds();

    for (final seed in seeds) {
      exercises.add(_fromSeed(seed));

      for (final rule in _variationRules) {
        if (rule.category == seed.primaryCategory &&
            rule.difficulty == seed.difficulty) {
          continue;
        }
        exercises.add(_fromVariation(seed, rule));
      }
    }

    return exercises;
  }
