/// Internal seed used to programmatically generate [Exercise] instances.
class _ExerciseSeed {
  const _ExerciseSeed({
    required this.slug,
    required this.name,
    required this.difficulty,
    required this.primaryCategory,
    required this.targetMuscles,
    required this.caloriesPerMinute,
    required this.durationMinutes,
    required this.sets,
    required this.reps,
    required this.restSeconds,
    required this.instructions,
    required this.commonMistakes,
    required this.tips,
  });

  final String slug;
  final String name;
  final Difficulty difficulty;
  final ExerciseCategory primaryCategory;
  final List<MuscleGroup> targetMuscles;
  final double caloriesPerMinute;
  final int durationMinutes;
  final int sets;
  final String reps;
  final int restSeconds;
  final List<String> instructions;
  final List<String> commonMistakes;
  final List<String> tips;
}

/// Describes how a seed exercise is adapted into a category-specific variation.
class _VariationRule {
  const _VariationRule({
    required this.slugSuffix,
    required this.nameSuffix,
    required this.category,
    this.difficulty,
    this.caloriesMultiplier = 1.0,
    this.durationOffset = 0,
    this.setsOffset = 0,
    this.restOffset = 0,
    this.repsOverride,
  });

  final String slugSuffix;
  final String nameSuffix;
  final ExerciseCategory category;
  final Difficulty? difficulty;
  final double caloriesMultiplier;
  final int durationOffset;
  final int setsOffset;
  final int restOffset;
  final String? repsOverride;
}

/// Bodyweight exercise catalog with programmatic variation generation.
class ExerciseDatabase {
  ExerciseDatabase._();

  static List<Exercise>? _cache;

  static List<Exercise> getAllExercises() {
    _cache ??= _buildExercises();
    return List.unmodifiable(_cache!);
  }

  static Exercise? getById(String id) {
    try {
      return getAllExercises().firstWhere((e) => e.id == id);
    } catch (_) {
      return null;
    }
  }

  static List<Exercise> getByCategory(ExerciseCategory category) =>
      getAllExercises().where((e) => e.category == category).toList();

  static List<Exercise> getByDifficulty(Difficulty difficulty) =>
      getAllExercises().where((e) => e.difficulty == difficulty).toList();

  static List<Exercise> getByMuscle(MuscleGroup muscle) => getAllExercises()
      .where((e) => e.targetMuscles.contains(muscle))
      .toList();

  static List<Exercise> search(String query) {
    final normalized = query.trim().toLowerCase();
    if (normalized.isEmpty) return getAllExercises();
    return getAllExercises()
        .where(
          (e) =>
              e.name.toLowerCase().contains(normalized) ||
              e.categoryLabel.toLowerCase().contains(normalized) ||
              e.difficultyLabel.toLowerCase().contains(normalized) ||
              e.targetMuscles.any(
                (m) => m.name.toLowerCase().contains(normalized),
              ),
        )
        .toList();
  }

  static double _clampCalories(double value) => value.clamp(4.0, 12.0);

  static int _clampDuration(int value) => value.clamp(3, 15);

  static int _clampSets(int value) => value.clamp(3, 5);

  static int _clampRest(int value) => value.clamp(30, 90);

  static Exercise _fromSeed(_ExerciseSeed seed, {String? idOverride}) {
    return Exercise(
      id: idOverride ?? seed.slug,
      name: seed.name,
      category: seed.primaryCategory,
      difficulty: seed.difficulty,
      targetMuscles: seed.targetMuscles,
      caloriesPerMinute: _clampCalories(seed.caloriesPerMinute),
      durationMinutes: _clampDuration(seed.durationMinutes),
      sets: _clampSets(seed.sets),
      reps: seed.reps,
      restSeconds: _clampRest(seed.restSeconds),
      instructions: seed.instructions,
      commonMistakes: seed.commonMistakes,
      tips: seed.tips,
    );
  }

  static Exercise _fromVariation(_ExerciseSeed seed, _VariationRule rule) {
    return Exercise(
      id: '${seed.slug}${rule.slugSuffix}',
      name: '${seed.name}${rule.nameSuffix}',
      category: rule.category,
      difficulty: rule.difficulty ?? seed.difficulty,
      targetMuscles: seed.targetMuscles,
      caloriesPerMinute:
          _clampCalories(seed.caloriesPerMinute * rule.caloriesMultiplier),
      durationMinutes:
          _clampDuration(seed.durationMinutes + rule.durationOffset),
      sets: _clampSets(seed.sets + rule.setsOffset),
      reps: rule.repsOverride ?? seed.reps,
      restSeconds: _clampRest(seed.restSeconds + rule.restOffset),
      instructions: seed.instructions,
      commonMistakes: seed.commonMistakes,
      tips: seed.tips,
    );
  }

